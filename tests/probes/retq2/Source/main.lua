local function show(name, ...)
  local r = table.pack(...)
  local s = {}
  for i = 1, r.n do local v = r[i] s[#s + 1] = (type(v) == "userdata" and (getmetatable(v) or {}).__name or tostring(v)) .. (math.type(v) and ("/" .. math.type(v)) or "") end
  fh:write(name .. " n=" .. r.n .. " " .. table.concat(s, " | ") .. "\n")
end
