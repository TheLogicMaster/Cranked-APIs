-- Probe: setting and reading unknown fields on menu items, pathfinder nodes and graphs, and other native objects
local gfx = playdate.graphics
local fh = playdate.file.open("out.txt", playdate.file.kFileWrite)
local function try(name, f)
  local ok, err = pcall(f)
  fh:write(name .. " " .. tostring(ok) .. " " .. tostring(err):gsub("^[^:]*:%d+: ", "") .. "\n")
end
local menu = playdate.getSystemMenu()
local item = menu:addMenuItem("x", function() end)
try("item set foo", function() item.foo = 1 return item.foo end)
try("item set 1", function() item[1] = 1 return item[1] end)
try("item get bar", function() return item.bar end)
try("item set title", function() item.title = "y" return item.title end)
try("item set value", function() item.value = 3 return item.value end)
try("item set callback", function() item.callback = 5 return type(item.callback) end)
local g = playdate.pathfinder.graph.new2DGrid(3, 3)
local n = g:nodeWithXY(1, 1)
try("node set foo", function() n.foo = 1 return n.foo end)
try("node set 1", function() n[1] = 1 return n[1] end)
try("node set x str", function() n.x = "5" return n.x end)
try("node get bar", function() return n.bar end)
try("node set x", function() n.x = 9 return n.x end)
try("node set id", function() n.id = 9 return n.id end)
try("graph set foo", function() g.foo = 1 return g.foo end)
local img = gfx.image.new(4, 4)
try("image set foo", function() img.foo = 1 return img.foo end)
try("image set width", function() img.width = 9 return img.width end)
local s = gfx.sprite.new()
try("sprite set foo", function() s.foo = 1 return s.foo end)
try("sprite set x", function() s.x = 9 return s.x end)
local font = gfx.getSystemFont()
try("font set foo", function() font.foo = 1 return font.foo end)
local snd = playdate.sound.synth.new()
try("synth set foo", function() snd.foo = 1 return snd.foo end)
local t = playdate.timer and playdate.timer
local f = playdate.file.open("tmp.txt", playdate.file.kFileWrite)
try("file set foo", function() f.foo = 1 return f.foo end)
f:close()
menu:removeAllMenuItems()
fh:close()
function playdate.update() end
