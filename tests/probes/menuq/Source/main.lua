-- Probe: the system menu API: item limits, errors, titles, values, options, removal
local fh = playdate.file.open("out.txt", playdate.file.kFileWrite)
local function w(...) local t = {} for i = 1, select('#', ...) do t[#t + 1] = tostring((select(i, ...))) end fh:write(table.concat(t, " ") .. "\n") end
local m = playdate.getSystemMenu()
local a, ea = m:addMenuItem("Alpha", function() end)
local b, eb = m:addCheckmarkMenuItem("Beta", true, function(v) end)
local c, ec = m:addOptionsMenuItem("Gamma", { "one", "two", "three" }, "two", function(v) end)
w("a", a ~= nil, ea, "b", b ~= nil, eb, "c", c ~= nil, ec)
local ok, d, ed = pcall(m.addMenuItem, m, "Delta", function() end)
w("fourth", ok, d, ed)
w("count", #m:getMenuItems())
w("titles", a:getTitle(), b:getTitle(), c:getTitle())
w("values", a:getValue(), b:getValue(), c:getValue())
b:setValue(false) c:setValue("three") w("set", b:getValue(), c:getValue())
local ok2, e2 = pcall(c.setValue, c, "nope") w("bad option", ok2, e2, c:getValue())
c:setValue(1) w("numeric option", c:getValue())
a:setTitle("Alpha2") w("retitle", a:getTitle())
local ok3, e3 = pcall(m.addOptionsMenuItem, m, "Opt", {}, nil, nil) w("empty options", ok3, e3)
m:removeMenuItem(b)
w("after remove", #m:getMenuItems())
local e, ee = m:addMenuItem("Epsilon") w("no callback", e ~= nil, ee)
local long, el = m:addMenuItem(string.rep("x", 40), function() end) w("long", long ~= nil, el, long and #long:getTitle())
m:removeAllMenuItems() w("after removeAll", #m:getMenuItems())
local f = m:addCheckmarkMenuItem("Chk") w("checkmark default", f and f:getValue())
local g = m:addOptionsMenuItem("Opts", { "x", "y" }) w("options default", g and g:getValue())
local items = m:getMenuItems() local t = {} for _, it in ipairs(items) do t[#t + 1] = it:getTitle() end w("order", table.concat(t, ","))
local ok4, e4 = pcall(m.addMenuItem, m, nil, function() end) w("nil title", ok4, e4)
fh:close()
function playdate.update() end
