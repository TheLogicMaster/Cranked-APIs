-- Probe: whether getters return the same Lua value each time (rawequal and ==) for images, tables, fonts
local gfx = playdate.graphics
local fh = playdate.file.open("out.txt", playdate.file.kFileWrite)
local function same(name, a, b) fh:write(name .. " rawequal=" .. tostring(rawequal(a, b)) .. " eq=" .. tostring(a == b) .. " type=" .. type(a) .. "\n") fh:flush() end
local img = gfx.image.new(4, 4)
local s = gfx.sprite.new(img)
same("sprite:getImage", s:getImage(), s:getImage())
same("sprite:getImage vs set", s:getImage(), img)
local t = gfx.imagetable.new(3)
t:setImage(1, img)
same("imagetable:getImage", t:getImage(1), t:getImage(1))
same("imagetable[1]", t[1], t[1])
same("imagetable get vs set", t:getImage(1), img)
same("getFont", gfx.getFont(), gfx.getFont())
same("getSystemFont", gfx.getSystemFont(), gfx.getSystemFont())
local f = gfx.font.new("/System/Fonts/Asheville-Sans-14-Bold")
gfx.setFont(f)
same("setFont then getFont", gfx.getFont(), f)
same("getMaskImage", img:getMaskImage(), img:getMaskImage())
same("getDisplayImage", gfx.getDisplayImage(), gfx.getDisplayImage())
same("getWorkingImage", gfx.getWorkingImage(), gfx.getWorkingImage())
local tm = gfx.tilemap.new() tm:setImageTable(t)
same("sprite.getAllSprites[1]", (s:add() or gfx.sprite.getAllSprites()[1]), gfx.sprite.getAllSprites()[1])
same("getAllSprites vs s", gfx.sprite.getAllSprites()[1], s)
local snd = playdate.sound.getHeadphoneState and playdate.sound.playingSources and playdate.sound.playingSources()
same("timer?", playdate.timer, playdate.timer)
local menu = playdate.getSystemMenu()
local item = menu:addMenuItem("x", function() end)
same("getMenuItems", menu:getMenuItems()[1], item)
same("menu", playdate.getSystemMenu(), playdate.getSystemMenu())
local g = playdate.pathfinder.graph.new2DGrid(2, 2)
same("nodeWithXY", g:nodeWithXY(1, 1), g:nodeWithXY(1, 1))
same("node:connectedNodes", g:nodeWithXY(1, 1):connectedNodes()[1], g:nodeWithXY(2, 1))
local syn = playdate.sound.synth.new()
local ch = playdate.sound.channel.new() ch:addSource(syn)
local seq = playdate.sound.sequence.new() local tr = playdate.sound.track.new() seq:addTrack(tr)
same("seq:getTrackAtIndex", seq:getTrackAtIndex(1), tr)
menu:removeAllMenuItems()
fh:close()
function playdate.update() end
