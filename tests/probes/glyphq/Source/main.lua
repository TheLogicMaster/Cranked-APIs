-- Probe: which code points the text drawer skips (no glyph, no advance)
local gfx = playdate.graphics
local fh = playdate.file.open("out.txt", playdate.file.kFileWrite)
local cps = {0x300, 0x301, 0x30F, 0x34F, 0x36F, 0x370, 0x483, 0x591, 0x64B, 0x200B, 0x200C, 0x200D, 0x200E, 0x200F, 0x2028, 0x2029, 0x202A, 0x202E, 0x2060, 0x2061, 0x2064, 0x2066, 0x206F, 0xFE00, 0xFE01, 0xFE0E, 0xFE0F, 0xFE10, 0xFE20, 0xFE2F, 0xFEFF, 0x180E, 0xAD, 0x1AB0, 0x1DC0, 0x20D0, 0x20FF, 0xE0001, 0xE0100, 0x1F3FB, 0x1F3FF, 0xE007F, 0x3099, 0x115F, 0x1160, 0x2E3A}
for _, cp in ipairs(cps) do
  local s = "A" .. utf8.char(cp) .. "B"
  local w, h = gfx.getTextSize(s)
  fh:write(string.format("%X", cp) .. " " .. w .. " " .. h .. "\n")
end
fh:close()
function playdate.update() end
