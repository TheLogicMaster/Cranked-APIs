-- Argument validation checks: API calls with odd arguments (cases found by the fuzzers in tests/tools).
-- Each case prints "name: ok" or "name: error". No case may crash the host.
import "CoreLibs/graphics"
local gfx = playdate.graphics
local out = playdate.file.open("out.txt", playdate.file.kFileWrite)
local function print(t) out:write(t .. "\n") end
local function e(name, f) local ok, err = pcall(f); print(name .. ": " .. (ok and "ok" or "error")); lastError = err end
e("graph.addNode nil", function() local g = playdate.pathfinder.graph.new(); g:addNode(1, nil) end)
e("node:addConnection nil", function() local g = playdate.pathfinder.graph.new(2); g:nodeWithID(1):addConnection(nil, 1, false) end)
e("image.setMaskImage nil", function() gfx.image.new(4, 4):setMaskImage(nil) end)
e("sprite.alphaCollision nil", function() local s = gfx.sprite.new(gfx.image.new(4, 4)); s:alphaCollision(nil) end)
e("sprite.setGroups 40", function() local s = gfx.sprite.new(); s:setGroups({40, -3, 2}); print("  mask " .. s:getGroupMask()) end)
e("image.blendWithImage nil", function() gfx.image.new(4, 4):blendWithImage(nil, 0.5, gfx.image.kDitherTypeBayer8x8) end)
e("image.blurredImage huge", function() gfx.image.new(8, 8, gfx.kColorBlack):blurredImage(100000, 1000000, gfx.image.kDitherTypeBayer8x8) end)
e("sample.getSubsample empty", function() local s = playdate.sound.sample.new(0.01); local sub = s:getSubsample(5, 5); print("  length " .. tostring(sub:getLength())) end)
e("new2DGrid huge", function() playdate.pathfinder.graph.new2DGrid(100000, 100000) end)
e("new2DGrid negative", function() playdate.pathfinder.graph.new2DGrid(-3, 4) end)
e("sprite huge collide rect", function()
    local big = gfx.sprite.new(); big:setSize(10, 10); big:moveTo(0, 0); big:setCollideRect(0, 0, 10000000, 10000000); big:add()
    local small = gfx.sprite.new(); small:setSize(4, 4); small:moveTo(5000, 6000); small:setCollideRect(0, 0, 4, 4); small:add()
    local t = playdate.getElapsedTime()
    print("  overlapping " .. #small:overlappingSprites() .. " at point " .. #gfx.sprite.querySpritesAtPoint(9000000, 9000000)
        .. " along line " .. #gfx.sprite.querySpritesAlongLine(-10, -10, 100, 100) .. " in rect " .. #gfx.sprite.querySpritesInRect(1, 1, 2, 2))
    local _, _, cols, n = small:moveWithCollisions(5010, 6000)
    print("  collisions " .. n .. " all " .. #gfx.sprite.allOverlappingSprites())
    big:setCollideRect(0, 0, 5, 5); print("  shrunk at point " .. #gfx.sprite.querySpritesAtPoint(9000000, 9000000) .. " near " .. #gfx.sprite.querySpritesAtPoint(1, 1))
    big:remove(); small:remove()
end)
e("image.drawRotated huge scale", function() local d = gfx.image.new(40, 40); gfx.pushContext(d); gfx.image.new(5, 3, gfx.kColorBlack):drawRotated(20, 20, 33, 1000000, 2000000); gfx.popContext(); print("  sample " .. d:sample(20, 20)) end)
e("image.rotatedImage huge scale", function() gfx.image.new(5, 3):rotatedImage(33, 1000000) end)
e("graph.removeNode nil", function() playdate.pathfinder.graph.new(2):removeNode(nil) end)
e("graph.addNewNodes huge", function() playdate.pathfinder.graph.new():addNewNodes(2000000) end)
e("tilemap huge position", function() local t = gfx.tilemap.new(); t:setSize(3, 3); t:setTileAtPosition(2, 1431655766, 5); print("  tile " .. tostring(t:getTileAtPosition(2, 1431655766))) end)
e("envelope trigger and getValue", function() local en = playdate.sound.envelope.new(0.1, 0.1, 0.5, 0.1); en:trigger(0.5); en:trigger(0.5, nil); en:trigger(2, 1); print("  value " .. tostring(en:getValue())) end)
e("perlin octaves inf", function() gfx.perlin(0.5, 0.5, 0.5, 0, math.huge, 0.5) end)
e("perlin octaves huge", function() print("  perlin " .. string.format("%.4f", gfx.perlin(0.3, 0.6, 0.9, 0, 2147483647, 0.5))) end)
e("perlinArray huge count", function() gfx.perlinArray(100000000, 0, 0.1) end)
e("graph.addNodes polygon", function() playdate.pathfinder.graph.new():addNodes(playdate.geometry.polygon.new(0, 0, 10, 0, 10, 10)) end)
e("channel addSource nil", function() local c = playdate.sound.channel.new(); print("  added " .. tostring(c:addSource(nil))); c:removeSource(nil) end)
e("fileplayer negative rate", function() local p = playdate.sound.fileplayer.new("assets/beep") or playdate.sound.fileplayer.new(); p:setRate(-1e9); p:play(); end)
print("last error: " .. tostring(lastError))
print("luaval done")
out:close()
function playdate.update() end
