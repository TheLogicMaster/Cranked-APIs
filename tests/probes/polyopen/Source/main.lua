-- Probe: open polygons through drawPolygon, fillPolygon, transforms and copies
local gfx = playdate.graphics
local geom = playdate.geometry
local fh = playdate.file.open("out.txt", playdate.file.kFileWrite)
local function rows(img)
  local w, h = img:getSize() local t = {}
  for y = 0, h - 1 do local r = {} for x = 0, w - 1 do r[#r + 1] = img:sample(x, y) == gfx.kColorBlack and "#" or "." end t[#t + 1] = table.concat(r) end
  return table.concat(t, "/")
end
local function show(label, f)
  local img = gfx.image.new(16, 16, gfx.kColorWhite)
  gfx.pushContext(img) gfx.setColor(gfx.kColorBlack) local ok, e = pcall(f) gfx.popContext()
  fh:write(label .. " " .. tostring(ok) .. " " .. tostring(e) .. " " .. rows(img) .. "\n")
end
local p = geom.polygon.new(4, 12, 2, 7, 4, 2)
fh:write("open closed=" .. tostring(p:isClosed()) .. " count=" .. p:count() .. "\n")
local t = geom.affineTransform.new() t:translate(5, 0)
local q = p * t
fh:write("p*t closed=" .. tostring(q:isClosed()) .. " count=" .. q:count() .. "\n")
local r = t:transformedPolygon(p)
fh:write("transformedPolygon closed=" .. tostring(r:isClosed()) .. "\n")
local c = p:copy() fh:write("copy closed=" .. tostring(c:isClosed()) .. "\n")
local tr = p:copy() tr:translate(1, 1) fh:write("translate closed=" .. tostring(tr:isClosed()) .. "\n")
show("draw open", function() gfx.drawPolygon(p) end)
show("draw open w1", function() gfx.drawPolygon(p, 1) end)
show("draw p*t", function() gfx.drawPolygon(q) end)
show("draw p*t w", function() gfx.drawPolygon(q, 0) end)
show("fill open", function() gfx.fillPolygon(p) end)
show("draw numbers", function() gfx.drawPolygon(4, 12, 2, 7, 4, 2) end)
local cl = geom.polygon.new(4, 12, 2, 7, 4, 2, 4, 12)
fh:write("explicit closed=" .. tostring(cl:isClosed()) .. " count=" .. cl:count() .. "\n")
local p2 = geom.polygon.new(4, 12, 2, 7, 4, 2) p2:close()
fh:write("close() closed=" .. tostring(p2:isClosed()) .. " count=" .. p2:count() .. "\n")
show("draw closed()", function() gfx.drawPolygon(p2) end)
local pts = geom.polygon.new(geom.point.new(1, 1), geom.point.new(8, 3), geom.point.new(3, 9))
fh:write("points closed=" .. tostring(pts:isClosed()) .. "\n")
show("draw pts", function() gfx.drawPolygon(pts) end)
show("line w0", function() gfx.setLineWidth(0) gfx.drawLine(2, 2, 13, 9) end)
show("line w1", function() gfx.setLineWidth(1) gfx.drawLine(2, 2, 13, 9) end)
show("poly w0 ctx", function() gfx.setLineWidth(0) gfx.drawPolygon(q) end)
show("poly w3 arg", function() gfx.drawPolygon(q, 3.7) end)
show("poly w ctx2", function() gfx.setLineWidth(2) gfx.drawPolygon(q) end)
show("poly closed w2", function() gfx.setLineWidth(2) gfx.drawPolygon(cl) end)
gfx.setLineWidth(1)
local one = geom.polygon.new(geom.point.new(7, 7))
fh:write("one count=" .. one:count() .. " closed=" .. tostring(one:isClosed()) .. "\n")
show("one w1", function() gfx.drawPolygon(one) end)
show("one w4", function() gfx.drawPolygon(one, 4) end)
show("one w5", function() gfx.drawPolygon(one, 5) end)
local fp = geom.polygon.new(1.6, 1.6, 12.4, 3.5, 6.5, 13.5, 1.6, 1.6)
show("frac draw", function() gfx.drawPolygon(fp) end)
show("frac fill", function() gfx.fillPolygon(fp) end)
show("frac fill nums", function() gfx.fillPolygon(1.6, 1.6, 12.4, 3.5, 6.5, 13.5) end)
show("frac draw nums", function() gfx.drawPolygon(1.6, 1.6, 12.4, 3.5, 6.5, 13.5) end)
show("fill 4 nums", function() gfx.fillPolygon(1, 2, 3, 4) end)
show("fill 5 nums", function() gfx.fillPolygon(1, 2, 3, 4, 9, 9, 1) end)
show("draw 1 num", function() gfx.drawPolygon(3) end)
show("draw 3 nums", function() gfx.drawPolygon(3, 3, 9) end)
show("draw 2 nums", function() gfx.drawPolygon(3, 3) end)
show("draw w nil", function() gfx.drawPolygon(q, nil) end)
for _, w in ipairs({ 2.5, 3.5, 2.4, 1.5, 0.5, -0.5, -1, 4.5, 0, 1, 2, 3, 4, 5 }) do show("poly width " .. w, function() gfx.drawPolygon(q, w) end) end
for _, w in ipairs({ 2.5, 3.5, 1.5, 0.5 }) do show("one width " .. w, function() gfx.drawPolygon(one, w) end) end
show("line w-1", function() gfx.setLineWidth(-1) gfx.drawLine(2, 2, 13, 9) end)
show("line w0 left", function() gfx.setLineWidth(0) gfx.drawLine(13, 2, 2, 9) end)
show("line w0 steep", function() gfx.setLineWidth(0) gfx.drawLine(13, 2, 9, 14) end)
show("line w0 flat", function() gfx.setLineWidth(0) gfx.drawLine(1, 5, 14, 5) end)
show("line w0 vert", function() gfx.setLineWidth(0) gfx.drawLine(5, 1, 5, 14) end)
show("rect w0", function() gfx.setLineWidth(0) gfx.drawRect(2, 2, 10, 8) end)
show("circle w0", function() gfx.setLineWidth(0) gfx.drawCircleAtPoint(8, 8, 5) end)
gfx.setLineWidth(1)
fh:close()
function playdate.update() end
