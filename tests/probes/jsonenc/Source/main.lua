-- Probe: json.encode and json.encodePretty edge cases
local f = playdate.file.open("out.txt", playdate.file.kFileWrite)
local function c(name, fn)
    f:write("START\t" .. name .. "\n"); f:flush()
    local ok, r = pcall(fn)
    if not ok then r = "ERR " .. tostring(r) end
    r = tostring(r):gsub("0x%x+", "ADDR"):gsub("\n", "\\n"):gsub("\t", "\\t")
    f:write(name .. "\t" .. r .. "\n"); f:flush()
end
local E, P = json.encode, json.encodePretty
c("empty", function() return E({}) end)
c("array", function() return E({1, 2, 3}) end)
c("holes", function() return E({[1] = 1, [3] = 3}) end)
c("hole5", function() return E({[5] = "x"}) end)
c("float keys only", function() return E({[1.0] = "a", [2] = "b"}) end)
c("mixed", function() return E({1, 2, x = 3}) end)
c("mixed pretty", function() return P({1, 2, x = 3}) end)
c("zero key", function() return E({[0] = "z", a = 1}) end)
c("neg key", function() return E({[-1] = "n", a = 1}) end)
c("frac key", function() return E({[2.5] = "f", a = 1}) end)
c("frac key over", function() return E({1, [2.5] = "f"}) end)
c("nested pretty", function() return P({a = {1, {b = 2}}, b = {}, c = "s"}) end)
c("nested pretty2", function() return P({{1, 2}, {}, {x = {}}}) end)
c("pretty empty", function() return P({}) end)
c("pretty array", function() return P({1, 2}) end)
c("sorted pretty", function() return P({zeta = 1, alpha = 2, mid = {c = 1, b = 2}}) end)
c("strings", function() return E({"q\"b\\s/\b\f\n\r\t\1\31\127 \195\169"}) end)
c("ints", function() return E({0, -5, 2147483647, -2147483648}) end)
c("floats", function() return E({0.1, 1.5, -2.25, 1e10, 3.14159265, 1/3, 1e-7, 123456.789}) end)
c("float big", function() return E({1e30, 3e38}) end)
c("inf", function() return E({math.huge, -math.huge}) end)
c("nan", function() return E({0/0}) end)
c("float int", function() return E({2.0, 1e9}) end)
c("bool", function() return E({true, false}) end)
c("function", function() return E({print}) end)
c("thread", function() return E({coroutine.create(function() end)}) end)
c("userdata", function() return E({playdate.graphics.image.new(2, 2)}) end)
c("recursion", function() local t = {}; t[1] = t; return E(t) end)
c("recursion obj", function() local t = {}; t.a = t; return E(t) end)
c("shared twice", function() local s = {1}; return E({s, s}) end)
c("top string", function() return E("hi") end)
c("top number", function() return E(1.5) end)
c("top int", function() return E(3) end)
c("top bool", function() return E(true) end)
c("top nil", function() return E(nil) end)
c("top function", function() return E(print) end)
c("number key big", function() return E({1, 2, [10] = 1}) end)
c("one key obj", function() return E({key = "v"}) end)
c("one key nested", function() return E({key = {inner = {1, 2}}}) end)
c("json null", function() return E({json.null}) end)
c("pretty strings key", function() return P({["a\"b"] = 1}) end)
c("meta tostring", function() return E(setmetatable({}, {__tostring = function() return "X" end})) end)
c("frac key pretty", function() return P({[2.5] = "f", a = 1}) end)
c("bool key", function() return E({[true] = 1}) end)
c("mixed keys pretty", function() return P({[2.5] = 1, a = 2}) end)
f:close()
playdate.stop()
function playdate.update() end
