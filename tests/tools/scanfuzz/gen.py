# Random scanf cases for parseString, differential against the host's sscanf.
# Writes cases.inc: one block per case; SCAN(n, input, format, args...) is defined by the probe (parseString) and the
# reference (sscanf); OUT(fmt, ...) logs. Inputs stay in range (no overflow), where the device and the host reference agree.
import random, sys
seed, count = int(sys.argv[1]), int(sys.argv[2])
rnd = random.Random(seed)
def word(n): return "".join(rnd.choice("abcxyz") for _ in range(n))
def conv(k):
    """returns (format, input text, declarations, address args, print statements)"""
    kind = rnd.choice(["d", "i", "u", "x", "o", "hd", "hhd", "hu", "hhu", "ld", "lld", "llu", "llx", "f", "lf", "e", "g", "s", "c", "set", "n"])
    sup = rnd.random() < 0.15 and kind != "n"
    v = "v%d" % k
    width = rnd.choice(["", "", "", str(rnd.randint(1, 6))])
    if kind in ("d", "i", "hd", "hhd", "ld", "lld"):
        lim = {"hhd": 100, "hd": 30000}.get(kind, 2000000000 if kind != "lld" else 9000000000000000000)
        val = rnd.randint(-lim, lim)
        text = str(val) if kind != "i" else rnd.choice([str(val), hex(abs(val)) if val >= 0 else str(val), "0%o" % abs(val)])
        ctype = {"hhd": "signed char", "hd": "short", "ld": "int", "lld": "long long"}.get(kind, "int")
        fmtkind = "ld" if kind == "ld" else kind  # %ld writes a 32-bit long on the device: the reference uses %d
        decl, pr = "%s %s = -77;" % (ctype, v), 'OUT(" %%lld", (long long) %s);' % v
        f = "%" + ("*" if sup else "") + width + kind
        ref_f = "%" + ("*" if sup else "") + width + ("d" if kind == "ld" else kind)
    elif kind in ("u", "x", "o", "hu", "hhu", "llu", "llx"):
        lim = {"hhu": 255, "hu": 65535, "llu": 2**63, "llx": 2**63}.get(kind, 4000000000)
        val = rnd.randint(0, lim)
        text = {"x": "%x" % val, "llx": "%x" % val, "o": "%o" % val}.get(kind, str(val))
        ctype = {"hhu": "unsigned char", "hu": "unsigned short", "llu": "unsigned long long", "llx": "unsigned long long"}.get(kind, "unsigned")
        decl, pr = "%s %s = 77;" % (ctype, v), 'OUT(" %%llu", (unsigned long long) %s);' % v
        f = ref_f = "%" + ("*" if sup else "") + width + kind
    elif kind in ("f", "lf", "e", "g"):
        val = rnd.choice(["1.5", "-0.25", "3", "1e3", "-2.5e-2", "12345.678", "0.1"])
        text = val
        ctype = "double" if kind == "lf" else "float"
        decl, pr = "%s %s = -7;" % (ctype, v), 'OUT(" %%.9g", (double) %s);' % v
        f = ref_f = "%" + ("*" if sup else "") + width + kind
    elif kind == "s":
        text = word(rnd.randint(1, 8))
        decl, pr = 'char %s[256] = "-";' % v, 'OUT(" [%%s]", %s);' % v
        f = ref_f = "%" + ("*" if sup else "") + width + "s"
    elif kind == "c":
        w = rnd.randint(1, 4) if width else 1
        text = word(rnd.randint(w, w + 2))
        decl, pr = 'char %s[8] = "-------";' % v, 'OUT(" [%%.7s]", %s);' % v
        f = ref_f = "%" + ("*" if sup else "") + (str(w) if width else "") + "c"
    elif kind == "set":
        chars = "".join(sorted(set(rnd.choice("abcxyz") for _ in range(3))))
        neg = rnd.random() < 0.3
        text = word(rnd.randint(1, 6))
        decl, pr = 'char %s[256] = "-";' % v, 'OUT(" [%%s]", %s);' % v
        f = ref_f = "%" + ("*" if sup else "") + width + "[" + ("^" if neg else "") + chars + "]"
    else:  # n
        text = ""
        decl, pr = "int %s = -77;" % v, 'OUT(" %%d", %s);' % v
        f = ref_f = "%n"
    # a width that cuts a number would leave out-of-range or partial values, where the device and the host
    # reference differ: numeric widths are at least the number's length
    if width and kind not in ("s", "c", "set", "n") and int(width) < len(text):
        nw = str(len(text) + rnd.randint(0, 2))
        f = f.replace(width, nw, 1); ref_f = ref_f.replace(width, nw, 1)
    if rnd.random() < 0.08: text = rnd.choice(["!", "", "zz", "-"]) + text  # sometimes a mismatch
    addr = [] if sup else [("&" if kind not in ("s", "c", "set") else "") + v]
    return f, ref_f, text, decl, addr, ([] if sup else [pr])
out = ["// generated by tools/scanfuzz/gen.py, seed %d" % seed]
for case in range(count):
    fmt = ref = text = ""; decls = []; addrs = []; prints = []
    for k in range(rnd.randint(1, 5)):
        f, rf, t, d, a, p = conv(k)
        sep = rnd.choice([" ", ",", ";", ""])
        if sep == "" and f[-1] not in "cn": sep = " "  # a number or word right after another would merge with it
        fmt += f + (sep if sep != " " else " "); ref += rf + (sep if sep != " " else " ")
        text += t + (sep if sep != " " else rnd.choice([" ", "  "]))
        decls.append(d); addrs += a; prints += p
    esc = lambda x: x.replace("\\", "\\\\").replace('"', '\\"')
    out.append("{ %s int n = -9; SCAN(n, \"%s\", \"%s\", \"%s\"%s); OUT(\"scan%d %%d\", n); %s OUT(\"\\n\"); }" % (
        " ".join(decls), esc(text), esc(fmt), esc(ref), "".join(", " + a for a in addrs), case, " ".join(prints)))
print("\n".join(out))
