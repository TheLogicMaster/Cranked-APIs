# Random printf cases for the fmtq probe (differential against the host's snprintf).
# Usage: python3 gen.py <seed> <count> > probe/cases.h
import random, sys
seed, count = int(sys.argv[1]), int(sys.argv[2])
rnd = random.Random(seed)
def conv():
    kind = rnd.choice(["d", "i", "u", "x", "X", "o", "hhd", "hd", "hhu", "hu", "lld", "llu", "llx", "f", "e", "g", "E", "G", "s", "c"])
    flags = "".join(rnd.sample("-+ #0", rnd.randint(0, 2)))
    if kind in ("s", "c"): flags = flags.replace("+", "").replace(" ", "").replace("#", "").replace("0", "")
    if kind in ("u", "x", "X", "o", "hhu", "hu", "llu", "llx"): flags = flags.replace("+", "").replace(" ", "")
    if kind[-1] in "di": flags = flags.replace("#", "")
    args = []
    width = rnd.choice(["", "", str(rnd.randint(1, 12)), "*"])
    if width == "*": args.append(("int", str(rnd.randint(-8, 12))))
    prec = "" if kind == "c" else rnd.choice(["", "", "." + str(rnd.randint(0, 8)), ".*"])
    if prec == ".*": args.append(("int", str(rnd.randint(0, 8))))
    if kind in ("s",):
        args.append(("str", '"' + "".join(rnd.choice("abcXYZ019 ") for _ in range(rnd.randint(0, 10))) + '"'))
    elif kind == "c":
        args.append(("int", "'" + rnd.choice("aZ0!") + "'"))
    elif kind in ("f", "e", "g", "E", "G"):
        args.append(("dbl", repr(rnd.choice([0.0, -0.5, 1.0 / 3, 12345.678, -1e-5, 1e10, 2.5, 123456789.125]))))
    elif kind.startswith("ll"):
        v = rnd.choice([0, 1, -1, 2**40 + 7, -(2**50), 2**63 - 1])
        if kind != "lld": v &= 2**64 - 1
        args.append(("ll", str(v) + ("ULL" if kind != "lld" else "LL")))
    else:
        v = rnd.choice([0, 1, -1, 42, 255, 256, 65535, 70000, -70000, 2**31 - 1])
        args.append(("int", str(v) + ("u" if kind in ("u", "x", "X", "o", "hhu", "hu") and v >= 0 else "")))
    return "%" + flags + width + prec + kind, args
print("// generated by tools/fmtfuzz/gen.py, seed %d" % seed)
print("#define CASES(X) \\")
for _ in range(count):
    fmt, args = "", []
    for _ in range(rnd.randint(1, 6)):
        f, a = conv(); fmt += f + rnd.choice(["|", " ", ""]); args += a
    print('  X("%s", %s) \\' % (fmt, ", ".join(v for _, v in args)))
print("")
